im = np.array(Image.open('src/sheet.png').convert('RGB')).astype(int)
os.makedirs('assets', exist_ok=True)
meta = {}
for k,(x0,y0,x1,y1) in B.items():
    c = im[y0:y1, x0:x1]
    R,G,Bc = c[...,0],c[...,1],c[...,2]
    bg = (Bc<=26)&(R<=14)&(G<=20)&(Bc-R>=3)
    if k.startswith('bg_'): bg[:] = False
    fg = ~bg
    lab,n = nd.label(fg)
    sizes = nd.sum(fg, lab, range(1,n+1))
    sl = nd.find_objects(lab)
    ok = [i+1 for i,s in enumerate(sizes) if s >= 10 and (sl[i][0].stop-sl[i][0].start) > 4 and (sl[i][1].stop-sl[i][1].start) > 3]
    keep = np.isin(lab, ok)
    ys,xs = np.where(keep)
    ya,yb,xa,xb = ys.min(), ys.max()+1, xs.min(), xs.max()+1
    rgba = np.zeros((yb-ya, xb-xa, 4), np.uint8)
    rgba[...,:3] = c[ya:yb, xa:xb]; rgba[...,3] = keep[ya:yb, xa:xb]*255
    Image.fromarray(rgba).save(f'assets/{k}.png', optimize=True)
    meta[k] = [int(xb-xa), int(yb-ya)]
json.dump(meta, open('src/meta.json','w'))
